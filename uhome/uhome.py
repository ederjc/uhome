class Number(Entity):
    """
    More information about MQTT Number: https://www.home-assistant.io/integrations/number.mqtt/

    Example:
        level = Number(device, "Target Level", min=0, max=100, step=5)
        level.set_action(lambda value: level.publish(value))
        level.publish(50)
    """

    entity_type = 'number'
    _action = None

    def make_conf(self, **kwargs):
        conf = Entity.make_conf(self, **kwargs)
        conf["stat_t"] = self.topic
        conf["cmd_t"] = self.topic_for('set')
        return conf

    def publish(self, payload, force=False):
        """
        @brief Publishes a payload to the MQTT state topic if it changed.

        @param payload: The data to be published. It will be converted to a string before publishing.
        @param force: Publish even if the payload did not change. Defaults to False.
        """
        return self._publish_state(payload, self.conf['stat_t'], force=force)

    def get_topic(self):
        return self.conf['cmd_t']

    def set_action(self, action):
        """
        @brief Set the action to be performed when the number value is changed.

        This method subscribes to the command topic specified in the configuration
        and sets the action to be executed when a message is received on that topic.

        @param action: A callable that takes one argument, the message received with the new number value.
        """
        self._action = action
        return self._subscribe(self.conf['cmd_t'], self._handle_action)

    def _handle_action(self, msg):
        if self._action and self._is_valid_value(msg):
            self._action(msg)

    def _is_valid_value(self, msg):
        try:
            value = float(msg)
        except (TypeError, ValueError):
            return False

        min_value = self.conf.get('min')
        max_value = self.conf.get('max')
        step = self.conf.get('step')

        try:
            if min_value is not None and value < float(min_value):
                return False
            if max_value is not None and value > float(max_value):
                return False
            if step is not None:
                step = float(step)
                if step <= 0:
                    return False
                base = float(min_value) if min_value is not None else 0.0
                steps = (value - base) / step
                nearest = round(steps)
                if abs(steps - nearest) > 0.000001:
                    return False
        except (TypeError, ValueError):
            return False
        return True
